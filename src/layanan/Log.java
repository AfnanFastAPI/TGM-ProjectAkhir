    private void setupPlaceholder(JTextField field, String teksPlaceholder) {
        field.setText(teksPlaceholder);
        field.setForeground(new java.awt.Color(153, 153, 153)); 

        if (field instanceof JPasswordField) {
            ((JPasswordField) field).setEchoChar((char) 0); 
        }

        field.addFocusListener(new java.awt.event.FocusListener() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                if (field.getText().equals(teksPlaceholder)) {
                    field.setText("");
                    field.setForeground(java.awt.Color.BLACK); 
                    
                    if (field instanceof JPasswordField) {
                        ((JPasswordField) field).setEchoChar('\u2022'); 
                    }
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent e) {
                if (field.getText().isEmpty()) {
                    field.setForeground(new java.awt.Color(153, 153, 153));
                    field.setText(teksPlaceholder);
                    
                    if (field instanceof JPasswordField) {
                        ((JPasswordField) field).setEchoChar((char) 0);
                    }
                }
            }
        });
    }
    
