public class RoundedButton extends JButton {

    private int arcWidth = 24;
    private int arcHeight = 24;

    private Color borderColor = new Color(203, 213, 225);
    private int borderThickness = 0;

    public RoundedButton() {
        super();
        setupDefaults();
    }

    public RoundedButton(String text) {
        super(text);
        setupDefaults();
    }

    private void setupDefaults() {
        setContentAreaFilled(false);
        setFocusPainted(false);
        setBorderPainted(false);
        setOpaque(false);
        setForeground(Color.WHITE);
        setFont(new Font("SansSerif", Font.PLAIN, 14));
        setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
    }

    public void setCornerRadius(int radius) {
        this.arcWidth = radius * 2;
        this.arcHeight = radius * 2;
        repaint();
    }

    public void setBorderColor(Color color) {
        this.borderColor = color;
        repaint();
    }

    public void setBorderThickness(int thickness) {
        this.borderThickness = Math.max(0, thickness);
        repaint();
    }

    @Override
    protected void paintComponent(Graphics g) {
        Graphics2D g2 = (Graphics2D) g.create();

        g2.setRenderingHint(
            RenderingHints.KEY_ANTIALIASING,
            RenderingHints.VALUE_ANTIALIAS_ON
        );

        Color bg = getBackground();

        if (getModel().isPressed()) {
            bg = bg.darker();
        } else if (getModel().isRollover()) {
            bg = bg.brighter();
        }

        g2.setColor(bg);

        int inset = borderThickness > 0 ? borderThickness / 2 : 0;

        g2.fill(new RoundRectangle2D.Float(
            inset, inset,
            getWidth() - 2f * inset,
            getHeight() - 2f * inset,
            arcWidth, arcHeight
        ));

        g2.dispose();

        super.paintComponent(g);
    }

    @Override
    protected void paintBorder(Graphics g) {
        if (borderThickness <= 0) {
            return;
        }

        Graphics2D g2 = (Graphics2D) g.create();

        g2.setRenderingHint(
            RenderingHints.KEY_ANTIALIASING,
            RenderingHints.VALUE_ANTIALIAS_ON
        );

        g2.setColor(borderColor);
        g2.setStroke(new BasicStroke(borderThickness));

        float inset = borderThickness / 2f;

        g2.draw(new RoundRectangle2D.Float(
            inset, inset,
            getWidth() - borderThickness,
            getHeight() - borderThickness,
            arcWidth, arcHeight
        ));

        g2.dispose();
    }
}
    
